const assert = require('node:assert/strict');
const { WORDS, evaluate, submit, normalize, createGame } = require('./dist/game.js');
assert.equal(new Set(WORDS).size, 12);
assert.ok(WORDS.every(word => word.length === 5 && /^[A-Z]+$/.test(word)));
assert.equal(createGame().answer.length, 5);
assert.equal(normalize('maçã'), 'MACA');
assert.deepEqual(evaluate('AAAAAA', 'BANANA'), ['absent', 'correct', 'absent', 'correct', 'absent', 'correct']);
assert.deepEqual(evaluate('ACABA', 'CASAS'), ['present', 'present', 'present', 'absent', 'absent']);
assert.deepEqual(evaluate('GATOS', 'GATOS'), Array(5).fill('correct'));
let game = {answer:'TERMO', guesses:[], status:'playing'};
assert.ok(submit(game, 'OI').error);
assert.ok(submit(game, '12345').error);
assert.equal(game.guesses.length, 0);
for (let i = 0; i < 6; i++) submit(game, 'LIVRO');
assert.equal(game.status, 'lost');
assert.ok(submit(game, 'TERMO').error);
assert.equal(game.guesses.length, 6);
game = {answer:'TERMO', guesses:[], status:'playing'};
submit(game, 'termo');
assert.equal(game.status, 'won');
assert.ok(submit(game, 'LIVRO').error);
game = {answer:'TERMO', guesses:[], status:'playing'};
for (let i = 0; i < 5; i++) submit(game, 'LIVRO');
submit(game, 'TERMO');
assert.equal(game.status, 'won');
console.log('Todos os testes passaram: palavras, acentos, cores, repetição, validação e fim de jogo.');
